let language = document.documentElement.lang === "de" ? "de" : "en";
function t(key, ...values) {
  let text = TEXTS[language][key] ?? TEXTS.en[key] ?? key;
  if (text && typeof text === "object") text = text[state.device] ?? text[state.device === "hand" || state.device === "bhand" ? "hand" : "glove"];
  return typeof text === "function" ? text(...values) : text;
}
const channelName = id => t("kanal_" + CHANNEL[id].k);

// Set all fixed texts in the current language (at start, when switching language or board).
function setTexts() {
  document.documentElement.lang = language;
  document.title = t("titel");
  for (const el of document.querySelectorAll("[data-t]")) el.textContent = t(el.dataset.t);
  for (const el of document.querySelectorAll("[data-t-html]")) el.innerHTML = t(el.dataset.tHtml);
  for (const el of document.querySelectorAll("[data-t-title]")) el.title = t(el.dataset.tTitle);
  for (const el of document.querySelectorAll("[data-t-aria]")) el.setAttribute("aria-label", t(el.dataset.tAria));
  $("sprache").value = language;
  $("verbinden").textContent = t(connections.length ? "trennen" : "verbinden");
  $("demo").textContent = t(state.source === "demo" ? "demoStoppen" : "demo");
  showTheme();
  showDetection();
  setStatus(state.statusKey, state.statusKind);
  showTarget();
  if ($("kal").open) renderCalibration();
  toolTexts();
  showCreep();
}

// Creep compensation button: shows what the glove reported ("Creep compensation on/off", from "i" and "d")
function showCreep() {
  const c = viewConn();
  const on = c ? c.creep : state.source === "demo" ? demo.creep : undefined;
  $("kriechKnopf").textContent = t(on === undefined ? "kriech" : on ? "kriechAn" : "kriechAus");
  $("kriechKnopf").setAttribute("aria-pressed", on === true);
}

function prepare(canvas) {
  const r = canvas.getBoundingClientRect();
  const dpr = window.devicePixelRatio || 1;
  const w = Math.max(1, Math.round(r.width * dpr)), h = Math.max(1, Math.round(r.height * dpr));
  if (canvas.width !== w || canvas.height !== h) { canvas.width = w; canvas.height = h; }
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, r.width, r.height);
  return { ctx, w: r.width, h: r.height };
}

// Status at the top left, key from TEXTS ("st_..."). Only rewritten when it changes.
function setStatus(key, kind) {
  state.statusKey = key;
  state.statusKind = kind || "";
  const s = $("status"), text = t(key);
  if (s.textContent !== text) s.textContent = text;
  if (s.dataset.art !== state.statusKind) s.dataset.art = state.statusKind;
}

function log(text) {
  const el = $("log");
  const atBottom = el.scrollTop + el.clientHeight >= el.scrollHeight - 4;
  el.textContent += text + "\n";
  if (el.textContent.length > 30000) el.textContent = el.textContent.slice(-20000);
  if (atBottom) el.scrollTop = el.scrollHeight;
}
